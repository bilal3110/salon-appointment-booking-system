const CDN = 'https://unpkg.com/lucide-static@latest/icons';

async function fetchIcon(name) {
    const res = await fetch(`${CDN}/${name}.svg`);
    if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
    const svg = await res.text();

    // Match the root <svg ...> wrapper and keep only its children.
    const match = /<svg\b[^>]*>([\s\S]*)<\/svg>/.exec(svg);
    if (!match) throw new Error(`${name}: could not parse svg`);

    const inner = match[1].trim();
    const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1] ?? '0 0 24 24';
    return { inner, viewBox };
}

const symbols = [];
const failed = [];

for (const name of ICONS) {
    try {
        const { inner, viewBox } = await fetchIcon(name);
        symbols.push(
            `    <symbol id="i-${name}" viewBox="${viewBox}" fill="none" stroke="currentColor"\n` +
                `        stroke-linecap="round" stroke-linejoin="round">\n` +
                `        ${inner.replace(/\n\s*/g, '\n        ')}\n` +
                `    </symbol>`
        );
    } catch (err) {
        failed.push(`${name} (${err.message})`);
    }
}

const blade = `{{-- Lucide icon sprite (ISC). Generated by tools/build-icons.mjs - do not edit by hand. --}}
<svg xmlns="http://www.w3.org/2000/svg" class="icon-sprite" fill="none" stroke="currentColor" stroke-width="2"
    stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">
${symbols.join('\n')}
</svg>
`;

writeFileSync(outFile, blade, 'utf8');

console.log(`Wrote ${symbols.length} icons to ${outFile}`);
if (failed.length) {
    console.log(`FAILED (${failed.length}):`);
    failed.forEach((f) => console.log('  - ' + f));
    process.exitCode = 1;
}
